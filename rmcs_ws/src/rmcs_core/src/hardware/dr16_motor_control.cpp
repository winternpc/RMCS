#include <cmath>
#include <cstdint>
#include <memory>

#include <rclcpp/node.hpp>
#include <rmcs_executor/component.hpp>

#include "controller/pid/pid_calculator.hpp"
#include "filter/low_pass_filter.hpp"

#include "hardware/device/dji_motor.hpp"
#include "hardware/device/dr16.hpp"

#include "librmcs/board/c_board.hpp"


namespace rmcs_core::hardware {

// ============================================================
// 第二周任务二：DR16 控制 M3508 速度闭环
// ============================================================
//
// 控制链：
//
// DR16 左摇杆 Y
//      ↓
// target_velocity_
//      ↓
// target - filtered
//      ↓
// velocity_error_
//      ↓
// PidCalculator
//      ↓
// control_torque_
//      ↓
// DjiMotor::generate_command()
//      ↓
// CAN1 / 0x200
//      ↓
// C620 ID = 3
//      ↓
// M3508
//
// 反馈链：
//
// M3508
//      ↓
// C620 反馈 ID = 0x203
//      ↓
// motor_.velocity()
//      ↓
// LowPassFilter
//      ↓
// filtered_velocity_
//      ↓
// 回到 PID
//
class Dr16MotorControl
    : public rmcs_executor::Component
    , public rclcpp::Node
    , public librmcs::board::CBoard::Callback {

public:
    Dr16MotorControl()
        : Node{
              get_component_name(),
              rclcpp::NodeOptions{}
                  .automatically_declare_parameters_from_overrides(true)
          } {

        // --------------------------------------------------------
        // 1. 读取最大目标速度
        // --------------------------------------------------------
        max_target_velocity_ =
            get_parameter("max_target_velocity").as_double();


        // --------------------------------------------------------
        // 2. 读取低通滤波截止频率
        // --------------------------------------------------------
        velocity_filter_cutoff_hz_ =
            get_parameter("velocity_filter_cutoff_hz").as_double();


        // --------------------------------------------------------
        // 3. 配置速度低通滤波器
        // --------------------------------------------------------
        velocity_filter_.set_cutoff(
            velocity_filter_cutoff_hz_,
            kUpdateFrequencyHz
        );

        // 当前：
        //
        // 截止频率 = 10 Hz
        // 采样频率 = 1000 Hz


        // --------------------------------------------------------
        // 4. 创建速度 PID
        // --------------------------------------------------------
        velocity_pid_ =
            controller::pid::make_pid_calculator(
                *this,
                "velocity_"
            );

        // 它会读取 YAML 中：
        //
        // velocity_kp
        // velocity_ki
        // velocity_kd
        //
        // velocity_integral_min
        // velocity_integral_max
        //
        // velocity_integral_split_min
        // velocity_integral_split_max
        //
        // velocity_output_min
        // velocity_output_max


        // --------------------------------------------------------
        // 5. 配置 M3508
        // --------------------------------------------------------
        motor_.configure(
            device::DjiMotor::Config{
                device::DjiMotor::Type::kM3508,
                3
            }
        );

        // 当前实机：
        //
        // C620 ID = 3
        //
        // 因此反馈：
        //
        // CAN ID = 0x203
        //
        // 控制：
        //
        // CAN ID = 0x200
        // 第三个 Quarter


        // --------------------------------------------------------
        // 6. 创建 CBoard
        // --------------------------------------------------------
        board_ =
            std::make_unique<librmcs::board::CBoard>(
                *this,
                get_parameter("board_serial").as_string()
            );
    }


    // ============================================================
    // RMCS 每周期更新
    // ============================================================
    void update() override {

        // --------------------------------------------------------
        // 1. 更新 DR16 状态
        // --------------------------------------------------------
        dr16_.update_status();


        // --------------------------------------------------------
        // 2. DR16 左摇杆 Y → 目标速度
        // --------------------------------------------------------
        if (dr16_.valid()) {

            const double joystick_y =
                dr16_.joystick_left().y();


            // ----------------------------------------------------
            // 摇杆死区
            // ----------------------------------------------------
            //
            // 遥控器机械摇杆回到中位之后，
            // 数值未必永远刚好是 0。
            //
            // 例如可能出现：
            //
            // 0.01
            // -0.02
            // 0.03
            //
            // 如果我们完全不处理，
            // 电机可能一直收到一个很小的目标速度。
            //
            // 所以规定：
            //
            // |joystick| < 0.05
            //
            // 就直接认为摇杆处于中间。
            if (std::abs(joystick_y) < kJoystickDeadzone) {

                target_velocity_ = 0.0;

            } else {

                // 正常区域：
                //
                // 摇杆比例
                // ×
                // 最大目标速度
                //
                // 得到目标速度。
                target_velocity_ =
                    joystick_y
                    * max_target_velocity_;
            }

        } else {

            // ----------------------------------------------------
            // DR16 掉线保护
            // ----------------------------------------------------
            //
            // 遥控器失效时：
            //
            // 目标速度立即变成 0。
            target_velocity_ = 0.0;
        }


        // --------------------------------------------------------
        // 3. 更新电机反馈
        // --------------------------------------------------------
        motor_.update_status();


        // --------------------------------------------------------
        // 4. 原始速度 → 低通滤波
        // --------------------------------------------------------
        if (motor_feedback_found_) {

            // 从 DjiMotor 获取当前速度。
            raw_velocity_ =
                motor_.velocity();


            // 使用低通滤波器滤掉部分速度噪声。
            filtered_velocity_ =
                velocity_filter_.update(
                    raw_velocity_
                );

        } else {

            // 还没有收到过真实电机反馈。
            raw_velocity_ = 0.0;
            filtered_velocity_ = 0.0;

            // 防止使用之前遗留的数据。
            velocity_filter_.reset();
        }


        // --------------------------------------------------------
        // 5. PID 闭环计算
        // --------------------------------------------------------
        //
        // 只有满足：
        //
        // ① DR16 有效
        // ② 电机已经收到反馈
        //
        // 才允许控制电机。
        if (
            dr16_.valid()
            && motor_feedback_found_
        ) {

            // ----------------------------------------------------
            // 摇杆回中时清除 PID 积分历史
            // ----------------------------------------------------
            //
            // 这是本次修改的重点。
            //
            // 前面的实机测试出现过：
            //
            // target = 0
            // error  = 0
            //
            // 但：
            //
            // torque_cmd = 0.05
            //
            // 原因就是积分项仍然保存着过去的误差。
            //
            // 当操作者已经松开摇杆时，
            // 我们希望之前积累的积分不要继续影响电机。
            //
            // 所以目标速度回到 0 时，
            // 清除 PID 历史。
            if (target_velocity_ == 0.0) {

                velocity_pid_.reset();
            }


            // ----------------------------------------------------
            // 速度误差
            // ----------------------------------------------------
            //
            // error = target - actual
            //
            velocity_error_ =
                target_velocity_
                - filtered_velocity_;


            // ----------------------------------------------------
            // PID 计算
            // ----------------------------------------------------
            //
            // 注意：
            //
            // 即使刚才 reset()，
            // 这里仍然会执行一次 PID。
            //
            // 所以如果：
            //
            // target = 0
            //
            // 但电机还在转：
            //
            // filtered_velocity != 0
            //
            // P 项依然会产生反方向控制，
            // 帮助电机停下来。
            control_torque_ =
                velocity_pid_.update(
                    velocity_error_
                );

        } else {

            // ----------------------------------------------------
            // 安全状态
            // ----------------------------------------------------
            //
            // DR16 掉线
            // 或者
            // 没有电机反馈
            //
            // 都不允许产生控制力矩。
            velocity_error_ = 0.0;
            control_torque_ = 0.0;


            // 同时清空 PID 历史。
            velocity_pid_.reset();
        }


        // --------------------------------------------------------
        // 6. 把控制量真正发送到 C620
        // --------------------------------------------------------
        command_update();


        // --------------------------------------------------------
        // 7. 每秒打印一次状态
        // --------------------------------------------------------
        ++status_log_counter_;

        if (status_log_counter_ >= 1000) {

            status_log_counter_ = 0;

            RCLCPP_INFO(
                get_logger(),

                "DR16=%s, "
                "joy=%.3f, "
                "target=%.3f, "
                "raw=%.3f, "
                "filtered=%.3f, "
                "error=%.3f, "
                "torque_cmd=%.3f",

                dr16_.valid()
                    ? "valid"
                    : "invalid",

                dr16_.joystick_left().y(),

                target_velocity_,

                raw_velocity_,

                filtered_velocity_,

                velocity_error_,

                control_torque_
            );
        }
    }


    // ============================================================
    // 发送 M3508 控制 CAN 帧
    // ============================================================
    void command_update() {

        // --------------------------------------------------------
        // start_transmit()
        // --------------------------------------------------------
        //
        // 这一部分直接仿照当前主线 flight.cpp。
        //
        // start_transmit()
        //
        // 会建立一次 CBoard 发送过程。
        auto builder =
            board_->start_transmit();


        // --------------------------------------------------------
        // CAN1 / ID 0x200
        // --------------------------------------------------------
        builder.can_transmit(
            Spec::kCans.kCan1,
            {
                .can_id = 0x200,

                .can_data =
                    device::CanPacket8{

                        // ----------------------------------------
                        // 第 1 个 Quarter
                        //
                        // C620 ID = 1
                        // ----------------------------------------
                        device::CanPacket8::PaddingQuarter{},


                        // ----------------------------------------
                        // 第 2 个 Quarter
                        //
                        // C620 ID = 2
                        // ----------------------------------------
                        device::CanPacket8::PaddingQuarter{},


                        // ----------------------------------------
                        // 第 3 个 Quarter
                        //
                        // C620 ID = 3
                        //
                        // 这就是我们的 M3508。
                        // ----------------------------------------
                        motor_.generate_command(
                            control_torque_
                        ),


                        // ----------------------------------------
                        // 第 4 个 Quarter
                        //
                        // C620 ID = 4
                        // ----------------------------------------
                        device::CanPacket8::PaddingQuarter{},
                    }
                        .as_bytes(),
            }
        );
    }


    // ============================================================
    // DBUS / DR16 数据接收
    // ============================================================
    void uart_receive_callback(
        const Spec::Uart& uart,
        const View::Uart& data
    ) override {

        // 只处理 CBoard 的 DBUS 口。
        if (uart != Spec::kUarts.kDbus) {
            return;
        }


        // --------------------------------------------------------
        // 第一次收到 DBUS 数据时打印提示
        // --------------------------------------------------------
        if (!dbus_packet_found_) {

            RCLCPP_INFO(
                get_logger(),
                "DBUS packet received, size = %zu bytes",
                data.uart_data.size()
            );

            dbus_packet_found_ = true;
        }


        // --------------------------------------------------------
        // 保存 DR16 原始数据
        // --------------------------------------------------------
        //
        // 后续 dr16_.update_status()
        //
        // 会解析这些数据。
        dr16_.store_status(
            data.uart_data.data(),
            data.uart_data.size()
        );
    }


    // ============================================================
    // CAN 电机反馈接收
    // ============================================================
    void can_receive_callback(
        const Spec::Can& can,
        const View::Can& data
    ) override {

        // --------------------------------------------------------
        // 当前 M3508 接在 CAN1
        // --------------------------------------------------------
        if (can != Spec::kCans.kCan1) {
            return;
        }


        // --------------------------------------------------------
        // 只接受正常 8 字节标准 CAN 帧
        // --------------------------------------------------------
        if (
            data.is_extended_can_id
            || data.is_remote_transmission
            || data.can_data.size() != 8
        ) {
            return;
        }


        // --------------------------------------------------------
        // 判断是不是当前 M3508 的反馈
        // --------------------------------------------------------
        //
        // 当前：
        //
        // M3508 ID = 3
        //
        // 所以：
        //
        // recv_id
        // =
        // 0x200 + 3
        // =
        // 0x203
        //
        const bool matched =
            motor_.match_then_store_status(
                data.can_id,
                data.can_data
            );


        // --------------------------------------------------------
        // 第一次检测到 M3508
        // --------------------------------------------------------
        if (
            matched
            && !motor_feedback_found_
        ) {

            RCLCPP_INFO(
                get_logger(),
                "M3508 feedback connected: CAN1, ID = 0x%03X",
                static_cast<unsigned int>(
                    data.can_id
                )
            );


            motor_feedback_found_ = true;


            // 第一次建立反馈时，
            // 清除之前可能存在的滤波历史。
            velocity_filter_.reset();


            // 同样清除 PID 历史。
            velocity_pid_.reset();
        }
    }


private:

    // ============================================================
    // RMCS 更新频率
    // ============================================================
    static constexpr double
        kUpdateFrequencyHz = 1000.0;


    // ============================================================
    // DR16 摇杆死区
    // ============================================================
    //
    // ±0.05 以内都认为回到中间。
    static constexpr double
        kJoystickDeadzone = 0.05;


    // ============================================================
    // 最大目标速度
    // ============================================================
    double max_target_velocity_ = 0.0;


    // ============================================================
    // 当前目标速度
    // ============================================================
    double target_velocity_ = 0.0;


    // ============================================================
    // 速度滤波截止频率
    // ============================================================
    double velocity_filter_cutoff_hz_ = 0.0;


    // ============================================================
    // 原始速度反馈
    // ============================================================
    double raw_velocity_ = 0.0;


    // ============================================================
    // 滤波后的速度
    // ============================================================
    double filtered_velocity_ = 0.0;


    // ============================================================
    // 速度误差
    // ============================================================
    double velocity_error_ = 0.0;


    // ============================================================
    // PID 最终输出
    // ============================================================
    //
    // 单位由 DjiMotor 的接口定义。
    //
    // 最后会传给：
    //
    // motor_.generate_command(control_torque_)
    //
    double control_torque_ = 0.0;


    // ============================================================
    // 速度低通滤波器
    // ============================================================
    filter::LowPassFilter<1>
        velocity_filter_{1.0};


    // ============================================================
    // 速度 PID
    // ============================================================
    controller::pid::PidCalculator
        velocity_pid_{};


    // ============================================================
    // 是否已经收到 DBUS
    // ============================================================
    bool dbus_packet_found_ = false;


    // ============================================================
    // 是否已经收到过 M3508 反馈
    // ============================================================
    bool motor_feedback_found_ = false;


    // ============================================================
    // 日志计数
    // ============================================================
    std::uint32_t status_log_counter_ = 0;


    // ============================================================
    // CBoard
    // ============================================================
    std::unique_ptr<librmcs::board::CBoard>
        board_;


    // ============================================================
    // DR16
    // ============================================================
    device::Dr16 dr16_;


    // ============================================================
    // M3508
    // ============================================================
    //
    // 第一个 *this：
    // 状态所属 Component
    //
    // 第二个 *this：
    // 命令所属 Component
    //
    // "/motor"：
    // 电机接口名称前缀
    //
    device::DjiMotor motor_{
        *this,
        *this,
        "/motor"
    };
};

} // namespace rmcs_core::hardware


